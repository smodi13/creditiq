import Link from "next/link";
import { Card, ClassBadge, PageTitle, StatusPill } from "@/components/ui";
import { getCompany } from "@/data/companies";
import { liveReconcile, type ReconRow } from "@/lib/recon";
// Static imports: the committed snapshots are bundled with the build, so the page needs no filesystem access at run time (works on Vercel / serverless).
import amcxSnap from "../../../../data/recon/amcx.json";
import bdnSnap from "../../../../data/recon/bdn.json";
import brightwaterSnap from "../../../../data/recon/brightwater.json";

const SNAPS: Record<string, unknown> = { amcx: amcxSnap, bdn: bdnSnap, brightwater: brightwaterSnap };

const IDS = ["amcx", "bdn", "brightwater"];
const fmt = (v: unknown, kind: string) => (typeof v === "number" ? (kind === "pct" ? `${(v * 100).toFixed(3)}%` : kind === "ratio" ? v.toFixed(4) : v.toFixed(3)) : v == null ? "n/a" : String(v));

export default function Reconciliation() {
  const data = IDS.map((id) => {
    const snap = SNAPS[id] as Parameters<typeof liveReconcile>[1] & { workbook: string; pass_count: number; total: number };
    const c = getCompany(id)!;
    return { id, c, snap, rows: liveReconcile(c, snap) as ReconRow[] };
  });
  return (
    <div className="space-y-3">
      <PageTitle title="Excel ⇄ web reconciliation" sub="Internal validation: Excel values come from the recalculated workbook (committed snapshot); web values are recomputed live by the TypeScript engine on every render. Any engine change that breaks agreement shows up here as FAIL." />
      {data.map(({ id, c, snap, rows }) => {
        const pass = rows.filter((r) => r.status === "PASS").length;
        return (
          <Card key={id} title={<span>{c.name} <ClassBadge k={c.dataClass} /></span>} right={<span className="text-[12px]"><b className={pass === rows.length ? "text-good" : "text-bad"}>{pass}/{rows.length} PASS</b> · <span className="text-muted">{snap.workbook}</span></span>}>
            <details>
              <summary className="cursor-pointer text-[12px] mb-2">Headline metrics (click for all {rows.length})</summary>
              <div className="overflow-x-auto max-h-[420px] overflow-y-auto"><table className="text-[11px]">
                <thead><tr><th>Metric</th><th className="num">Excel</th><th className="num">Web</th><th className="num">Difference</th><th className="num">Tolerance</th><th>Status</th></tr></thead>
                <tbody>{rows.map((r) => <tr key={r.key}><td>{r.label}</td><td className="num">{fmt(r.excel, r.kind)}</td><td className="num">{fmt(r.web, r.kind)}</td><td className="num">{r.diff == null ? "—" : r.diff.toExponential(1)}</td><td className="num text-muted">{r.tol}</td><td><StatusPill s={r.status} /></td></tr>)}</tbody>
              </table></div>
            </details>
            <table className="text-[12px]">
              <thead><tr><th>Metric</th><th className="num">Excel</th><th className="num">Web</th><th className="num">Difference</th><th>Status</th></tr></thead>
              <tbody>{rows.filter((r) => ["base.revenue.p1", "base.ebitda.p1", "base.fcf.sum", "downside.debt.p5", "ltm.netlev", "ltm.coverage", "base.irr", "downside.irr", "severe.recovery.target", "base.moic", "decision"].includes(r.key)).map((r) => <tr key={r.key}><td>{r.label}</td><td className="num">{fmt(r.excel, r.kind)}</td><td className="num">{fmt(r.web, r.kind)}</td><td className="num">{r.diff == null ? "—" : r.diff.toExponential(1)}</td><td><StatusPill s={r.status} /></td></tr>)}</tbody>
            </table>
          </Card>
        );
      })}
      <p className="text-[11px] text-muted">Method: both implementations follow the same formulas (interest on beginning balances, cash-first maturity repayment, market-access test, collateral-pool waterfall, IRR on annual flows). The Excel side is a different code path (formulas generated by <code>scripts/build_model.py</code>, calculated by LibreOffice); agreement is therefore an independent check. Regenerate with <code>npm run model:build &amp;&amp; npm run model:reconcile</code>. <Link href="/settings">Back to settings</Link></p>
    </div>
  );
}
